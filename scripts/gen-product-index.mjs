// scripts/gen-product-index.mjs - Writes a slim product index for client-side pages
// (search, compare, wishlist). It is served as a static, CDN-cached file (public/product-index.json)
// and fetched after page load, so the catalogue is never bundled into page JavaScript.
import fs from 'fs';
import crypto from 'crypto';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { PRODUCTS } = await import('../config/products.js');
const { buildBrands } = await import('../lib/brandsCore.js');

const cut = (s, n) => (s && s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…' : s);
// Slim index for the shop filters and wishlist. The first image is left out when it follows the usual naming
// (/images/products/<category>/<slug>.webp); lib/useProductIndex.js puts it back. Search runs on the server
// (/api/search) and compare has its own small file, so SKU, stock text and specs are not repeated here.
const conventional = (p) => p.images && p.images[0] === `/images/products/${p.category}/${p.slug}.webp`;
const slim = PRODUCTS.map((p) => ({
  slug: p.slug,
  name: p.name,
  brand: p.brand,
  category: p.category,
  sub: p.subcategory,
  price: p.price ?? null,
  originalPrice: p.originalPrice,
  badge: p.badge,
  rating: p.rating,
  reviewsCount: p.reviewsCount,
  shortDescription: cut(p.shortDescription || p.description, 100),
  images: conventional(p) ? undefined : p.images?.slice(0, 1) || [],
  imported: p.imported || undefined,
}));

// Compare picker file: only the hand-curated (not bulk-imported) products, with their spec tables.
const compareItems = PRODUCTS.filter((p) => !p.imported).map((p) => ({
  slug: p.slug,
  name: p.name,
  brand: p.brand,
  category: p.category,
  price: p.price ?? null,
  images: p.images?.slice(0, 1) || [],
  specs: p.specs,
}));

// The file name carries a content hash, so it can be cached for a year and a changed catalogue gets a new URL.
// Per-product last-modified dates for the sitemap: a product only gets a new date when its content changes.
const lastmodPath = path.join(root, 'data/lastmod.json');
let previous = {};
try { previous = JSON.parse(fs.readFileSync(lastmodPath, 'utf8')); } catch { previous = {}; }
const today = new Date().toISOString().slice(0, 10);
const lastmod = {};
for (const p of PRODUCTS) {
  const h = crypto.createHash('sha1').update(JSON.stringify([p.name, p.brand, p.sku, p.price, p.originalPrice, p.badge, p.subcategory, p.shortDescription, p.images])).digest('hex').slice(0, 8);
  const old = previous[p.slug];
  lastmod[p.slug] = old && old.h === h ? old : { h, d: today };
}
fs.writeFileSync(lastmodPath, JSON.stringify(lastmod));

const json = JSON.stringify(slim);
const hash = crypto.createHash('sha256').update(json).digest('hex').slice(0, 10);
const fileName = `product-index.${hash}.json`;
for (const f of fs.readdirSync(path.join(root, 'public'))) {
  if (/^product-index(.[0-9a-f]+)?.json$/.test(f)) fs.rmSync(path.join(root, 'public', f));
}
fs.writeFileSync(path.join(root, 'public', fileName), json);

const compareJson = JSON.stringify(compareItems);
const compareHash = crypto.createHash('sha256').update(compareJson).digest('hex').slice(0, 10);
const compareFile = `compare-index.${compareHash}.json`;
for (const f of fs.readdirSync(path.join(root, 'public'))) {
  if (f.startsWith('compare-index.') && f.endsWith('.json')) fs.rmSync(path.join(root, 'public', f));
}
fs.writeFileSync(path.join(root, 'public', compareFile), compareJson);
fs.writeFileSync(
  path.join(root, 'lib/compareIndexUrl.js'),
  `// Generated by scripts/gen-product-index.mjs - do not edit.
export const COMPARE_INDEX_URL = '/${compareFile}';
`
);
console.log(`[gen-product-index] ${compareItems.length} compare items written to public/${compareFile}`);
fs.writeFileSync(
  path.join(root, 'lib/productIndexUrl.js'),
  `// Generated by scripts/gen-product-index.mjs - do not edit.
export const PRODUCT_INDEX_URL = '/${fileName}';
`
);
// Brand list for the navigation menu: [name, slug, product count], content-hashed like the product index.
const brandRows = buildBrands(PRODUCTS).map((b) => [b.name, b.slug, b.count]);
const brandJson = JSON.stringify(brandRows);
const brandHash = crypto.createHash('sha256').update(brandJson).digest('hex').slice(0, 10);
const brandFile = `brands.${brandHash}.json`;
for (const f of fs.readdirSync(path.join(root, 'public'))) {
  if (/^brands(.[0-9a-f]+)?.json$/.test(f)) fs.rmSync(path.join(root, 'public', f));
}
fs.writeFileSync(path.join(root, 'public', brandFile), brandJson);
fs.writeFileSync(
  path.join(root, 'lib/brandsUrl.js'),
  `// Generated by scripts/gen-product-index.mjs - do not edit.
export const BRANDS_URL = '/${brandFile}';
`
);
console.log(`[gen-product-index] ${brandRows.length} brands written to public/${brandFile}`);
// the old bundled index is no longer used; remove it so it can't creep back into a bundle
fs.rmSync(path.join(root, 'data/products/index.json'), { force: true });
console.log(`[gen-product-index] ${slim.length} products written to public/${fileName}`);
